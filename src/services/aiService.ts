/**
 * 3. AI REVIEW SUMMARIZATION
 */
export async function generateAiReviewSummary(
  destinationName: string,
  reviews: { author: string; rating: number; comment: string }[]
): Promise<{ positivePoints: string[]; cautionPoints: string[]; tips: string }> {
  if (reviews.length === 0) {
    return {
      positivePoints: ['Belum ada ulasan yang cukup'],
      cautionPoints: ['Jadilah pengunjung pertama yang memberikan ulasan!'],
      tips: 'Pastikan selalu menjaga kebersihan pantai dan membawa kantong sampah sendiri.'
    };
  }

  const reviewTexts = reviews.map(r => `[Rating: ${r.rating}/5] ${r.comment}`).join('\n');
  const systemPrompt = `
Analisis ulasan pengunjung untuk destinasi pesisir "${destinationName}".
Ekstrak dalam format JSON murni:
{
  "positivePoints": ["3 poin keunggulan utama yang paling sering dipuji"],
  "cautionPoints": ["1-2 hal yang perlu diwaspadai atau dipersiapkan pengunjung"],
  "tips": "1 tips terbaik untuk calon wisatawan"
}
`;

  try {
    const raw = await callGeminiRaw(systemPrompt, reviewTexts);
    const cleaned = raw.replace(/```json/g, '').replace(/```/g, '').trim();
    return JSON.parse(cleaned);
  } catch (err) {
    return {
      positivePoints: ['Pemandangan laut alami dan asri', 'Spot foto pesisir sangat menarik'],
      cautionPoints: ['Perhatikan kebersihan dan cuaca gelombang'],
      tips: 'Datang di pagi hari untuk mendapatkan panorama terbaik dan terhindar dari terik matahari.'
    };
  }
}

