const GEMINI_API_KEY = (import.meta as any).env?.VITE_GEMINI_API_KEY || '';

/**
 * Helper to call Gemini API if key exists, or use algorithmic grounded synthesis
 */
async function callGeminiRaw(systemPrompt: string, userPrompt: string): Promise<string> {
  const apiKey = localStorage.getItem('pesisir_gemini_api_key') || GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error('API_KEY_NOT_SET');
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;
  
  const response = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [
        {
          role: 'user',
          parts: [
            { text: `${systemPrompt}\n\nUser Request: ${userPrompt}` }
          ]
        }
      ],
      generationConfig: {
        temperature: 0.2, // Low temperature for high factual accuracy
        topP: 0.8
      }
    })
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Gemini API Error: ${response.status} - ${errorText}`);
  }

  const data = await response.json();
  const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) {
    throw new Error('No content generated by Gemini');
  }
  return text;
}

